# Packs the sprite sheets from assets/ts into src/artData.ts (data URLs), so every build
# (Vite, the single-file play.html, Electron) gets the art without extra loaders.
import base64, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
art = open(os.path.join(root, 'src', 'art.ts'), encoding='utf-8').read()
names = re.findall(r"^\s*(\w+): '([\w.]+\.png)',", art, re.M)
out = ['// Generated by scripts/gen-art.py from assets/ts — do not edit by hand.', 'export const ART_DATA: Record<string, string> = {']
for key, file in names:
    data = base64.b64encode(open(os.path.join(root, 'assets', 'ts', file), 'rb').read()).decode()
    out.append(f"  {key}: 'data:image/png;base64,{data}',")
out.append('};\n')
open(os.path.join(root, 'src', 'artData.ts'), 'w', encoding='utf-8').write('\n'.join(out))
print(len(names), 'sheets packed')
